/* Diacríticos em linhas 1..4 */
#define DIACRITIC_ACUTE_LOWER       0
#define DIACRITIC_GRAVE_LOWER       1
#define DIACRITIC_CIRCUM_LOWER      2
#define DIACRITIC_TILDE_LOWER       3
#define DIACRITIC_TREMA_LOWER       4
#define DIACRITIC_CEDILLA_LOWER     5

#define DIACRITIC_ACUTE_UPPER       6
#define DIACRITIC_GRAVE_UPPER       7
#define DIACRITIC_CIRCUM_UPPER      8
#define DIACRITIC_TILDE_UPPER       9
#define DIACRITIC_TREMA_UPPER       10
#define DIACRITIC_CEDILLA_UPPER     11

static void apply_diacritic(uint8_t dest[16], const uint8_t base[16], int type) {
    memcpy(dest, base, 16);
    switch (type) {
        case DIACRITIC_ACUTE_LOWER:
            dest[2] = 0x0C; dest[3] = 0x18; dest[4] = 0x30;
            break;
        case DIACRITIC_GRAVE_LOWER:
            dest[2] = 0x30; dest[3] = 0x18; dest[4] = 0x0C;
            break;
        case DIACRITIC_CIRCUM_LOWER:
            dest[2] = 0x18; dest[3] = 0x3C; dest[4] = 0x66;
            break;
        case DIACRITIC_TILDE_LOWER:
            dest[2] = 0x74; dest[3] = 0x5C;
            break;
        case DIACRITIC_TREMA_LOWER:
            dest[2] = 0x66; dest[3] = 0x66;
            break;
        case DIACRITIC_CEDILLA_LOWER:
            dest[12] = 0x18; dest[13] = 0x18; dest[14] = 0x30;
            break;

        /* Para maiúsculas, o acento fica no topo (linhas 0..2) */
        case DIACRITIC_ACUTE_UPPER:
            dest[0] = 0x0C; dest[1] = 0x18; dest[2] |= 0x30;
            break;
        case DIACRITIC_GRAVE_UPPER:
            dest[0] = 0x30; dest[1] = 0x18; dest[2] |= 0x0C;
            break;
        case DIACRITIC_CIRCUM_UPPER:
            dest[0] = 0x18; dest[1] = 0x3C; dest[2] |= 0x66;
            break;
        case DIACRITIC_TILDE_UPPER:
            dest[0] = 0x74; dest[1] = 0x5C;
            break;
        case DIACRITIC_TREMA_UPPER:
            dest[0] = 0x66; dest[1] = 0x66;
            break;
        case DIACRITIC_CEDILLA_UPPER:
            dest[12] = 0x18; dest[13] = 0x18; dest[14] = 0x30;
            break;
    }
}

