static void emit_font(FILE *fp, const char *label, int mode) {
    fprintf(fp, "%s:\n", label);
    for (int i = 0; i < GLYPH_COUNT; i++) {
        uint8_t g[16];
        memcpy(g, base_glyphs[i], 16);
        int codepoint = 32 + i;

        if (mode == 0) {
            /* Modo 0: Folio Serif (Adiciona serifas clássicas no topo e base das hastes) */
            if (codepoint >= 'A' && codepoint <= 'Z') {
                if (codepoint == 'H' || codepoint == 'M' || codepoint == 'N' || codepoint == 'U' || codepoint == 'W' || codepoint == 'X' || codepoint == 'K') {
                    g[2] |= (g[2] << 1) | (g[2] >> 1);
                    g[11] |= (g[11] << 1) | (g[11] >> 1);
                } else if (codepoint == 'I') {
                    g[2] = 0x7E; g[11] = 0x7E;
                } else if (codepoint == 'A') {
                    g[11] = 0xE7;
                } else if (codepoint == 'L' || codepoint == 'B' || codepoint == 'D' || codepoint == 'E' || codepoint == 'F' || codepoint == 'P' || codepoint == 'R') {
                    g[2] |= 0x80; g[11] |= 0x80;
                }
            } else if (codepoint >= 'a' && codepoint <= 'z') {
                if (codepoint == 'm' || codepoint == 'n' || codepoint == 'u' || codepoint == 'h' || codepoint == 'k' || codepoint == 'r' || codepoint == 'p') {
                    g[5] |= 0x80;
                    g[11] |= (g[11] >> 1);
                } else if (codepoint == 'i' || codepoint == 'l') {
                    g[11] = 0x7E;
                }
            }
        } else if (mode == 1) {
            /* Modo 1: Clean Sans (Remove serifas para geometria pura) */
            if (codepoint == 'I' || codepoint == 'l') {
                for (int r = 2; r <= 11; r++) g[r] = 0x18;
            } else if (codepoint == 'i') {
                g[5] = 0x18; g[11] = 0x18;
            } else if (codepoint == '1') {
                g[11] = 0x18;
            } else if (codepoint == 'b' || codepoint == 'h' || codepoint == 'k') {
                g[2] = 0x60; g[11] &= 0x7E;
            } else if (codepoint == 'f' || codepoint == 'r' || codepoint == 'P' || codepoint == 'F' || codepoint == 'L') {
                g[2] &= 0x7F; g[11] &= 0x7F;
            }
        } else if (mode == 2) {
            /* Modo 2: Courier Slab (Serifas mecânicas largas de máquina de escrever em topo/base) */
            if ((codepoint >= 'A' && codepoint <= 'Z') || (codepoint >= 'a' && codepoint <= 'z') || codepoint >= 192) {
                g[11] |= (g[10] << 1) | (g[10] >> 1);
                if ((codepoint >= 'A' && codepoint <= 'Z') || (codepoint >= 192 && codepoint <= 223)) {
                    g[2] |= (g[3] << 1) | (g[3] >> 1);
                } else {
                    g[5] |= (g[6] << 1);
                }
            }
        }

        fprintf(fp, "    db ");
        for (int r = 0; r < 16; r++) {
            fprintf(fp, "0x%02X%s", g[r], (r < 15) ? "," : "");
        }
        fprintf(fp, " ; codepoint %d (0x%02X)\n", codepoint, codepoint);
    }
}

int main(void) {
    init_all_glyphs();

    FILE *fp = fopen("src/legacy/fonts.inc", "wb");
    if (!fp) return 1;
    fprintf(fp, "; =============================================================================\n");
    fprintf(fp, "; FOLIO-86 — Tabelas Tipográficas Gráficas 8x16 PT-BR (Serif, Sans, Courier Slab)\n");
    fprintf(fp, "; Total: 3 fontes x 224 glifos (32..255) x 16 bytes = 10.752 bytes\n");
    fprintf(fp, "; =============================================================================\n\n");
    emit_font(fp, "font_serif", 0);
    emit_font(fp, "font_sans",  1);
    emit_font(fp, "font_slab",  2);
    fclose(fp);
    printf("[OK] src/legacy/fonts.inc gerado com sucesso (3 familias de fontes PT-BR completas: 224 glifos cada).\n");
    return 0;
}
