sub file_of { my $l = shift; for (@LANGS) { return $_->[2] // "README.$_->[0].md" if $_->[0] eq $l } die $l }
sub lang_bar {
    my $cur = shift;
    return join ' · ', map { $_->[0] eq $cur ? "**$_->[1]**" : "[$_->[1]](" . file_of($_->[0]) . ")" } @LANGS;
}

